/**
 * When the things in the estate stop getting security updates.
 *
 * This is a bundled reference table, not a feed. That is a deliberate choice:
 * an external EOL API is one more thing to authenticate, rate-limit, cache and
 * be broken by, and the answer it returns changes about four times a year.
 * A table in the repository is auditable, works offline, and — because the
 * Administration screen writes overrides on top of it — is correctable by the
 * person who spots a wrong date without waiting for a release.
 *
 * Every date below was checked against the vendor's own lifecycle page in
 * September 2026; the `source` on each row is where it came from. Where a
 * vendor publishes both a mainstream and an extended date, `eol` is the date
 * security updates actually stop (the extended one) and `mainstream` carries
 * the earlier one, because a security tool that calls Server 2022 "end of
 * life" in October 2026 would be crying wolf for five years.
 *
 * WHAT IS DELIBERATELY NOT IN HERE
 *
 * - Internet Explorer 11. Its CPE is on 470 machines in this estate, and
 *   every one of them is a disabled OS component rather than a browser
 *   anybody runs. IE's retirement is also conditional -- IE mode in Edge is
 *   supported until 2029, and IE on an LTSC build follows that build's
 *   lifecycle. Flagging it would produce 470 false alarms.
 * - .NET Framework 3.5 and 4.7/4.8. They are Windows components and are
 *   supported for as long as the Windows underneath them is, so they have no
 *   date of their own. The genuinely retired 4.5.2/4.6/4.6.1 are listed.
 * - Anything whose retirement date the vendor has not published. Windows
 *   Server 23H2 is the live example: Microsoft's Annual Channel page still
 *   says "In Support" with no date. It is listed with a null date so the
 *   estate still counts those machines, under "no published date" rather
 *   than under a number somebody made up.
 *
 * @package VulnHub\Core
 */

